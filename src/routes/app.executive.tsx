import { createFileRoute } from "@tanstack/react-router";
import { PageHeader, Panel, Badge } from "@/components/lab/panel";
import { KpiRibbon } from "@/components/lab/kpi-ribbon";
import { LineTrend, HBar } from "@/components/lab/charts";
import { ProvinceHeatMap } from "@/components/lab/sa-map";
import { useAiRecommendations, useHomeKpis } from "@/lib/queries/dashboards";
import { Download } from "lucide-react";

export const Route = createFileRoute("/app/executive")({ component: Page });

// Page-local, illustrative-only chart series — no backend source built this pass.
const utilTrend = Array.from({length:12}).map((_,i)=>({ month: `M${i+1}`, Allocated: 100+i*4, Spent: 80+i*3 + (i%3)*4, Remaining: 20-i*0.5 }));
const heatData = ["Gauteng","KwaZulu-Natal","Western Cape","Eastern Cape","Limpopo","Mpumalanga","North West","Free State","Northern Cape"].map((p,i)=>({province:p, value: 78 - i*4}));
const programmeRate = ["Learnerships","Skills Programmes","Internships","Bursaries","Apprenticeships"].map((p,i)=>({province:p, spend: 75 - i*7}));

function Page() {
  const { data: kpis = [] } = useHomeKpis();
  const { data: aiRecommendations = [] } = useAiRecommendations();

  return (
    <>
      <PageHeader title="Executive Cockpit" subtitle="National view · FY 2026" actions={
        <>
          <select className="bg-muted border border-border rounded-md h-9 px-3 text-sm"><option>FY 2026</option></select>
          <select className="bg-muted border border-border rounded-md h-9 px-3 text-sm"><option>All provinces</option></select>
          <button className="text-sm px-3 py-2 rounded-md bg-primary text-primary-foreground inline-flex items-center gap-2"><Download className="size-4"/> Export</button>
        </>
      } />

      <KpiRibbon kpis={kpis} />

      <div className="grid lg:grid-cols-2 gap-6">
        <Panel title="National Skills Heat Map" subtitle="Completion rate by province" info={{
          what: "Completion rate for each province, shaded from low (red) to high (green) performance, so leadership can spot regional disparities at a glance.",
          calculation: "completions ÷ enrolments × 100 per province, for the selected financial year and programme filter.",
          source: "mart.completion_rates, grouped by province" }}>
          <ProvinceHeatMap data={heatData} />
        </Panel>
        <Panel title="Grant Utilisation Trend" subtitle="Allocated vs Spent vs Remaining (ZAR M)" info={{
          what: "Tracks how much of the approved grant budget has been allocated, spent, and remains unspent, month over month.",
          calculation: "Allocated = cumulative approved budget. Spent = cumulative confirmed disbursements. Remaining = Allocated − Spent.",
          source: "mart.grant_spending_summary" }}>
          <LineTrend data={utilTrend} keys={["Allocated","Spent","Remaining"]} />
        </Panel>
      </div>

      <div className="grid lg:grid-cols-3 gap-6">
        <Panel title="Completion Rate by Programme" info={{
          what: "Compares completion rate across CHIETA's five core programme types, to identify which delivery models are under-performing.",
          calculation: "completions ÷ enrolments × 100, grouped by programme type, current FY.",
          source: "mart.completion_rates, grouped by programme" }}>
          <HBar data={programmeRate} x="spend" y="province" />
        </Panel>
        <Panel title="Risk Summary" subtitle="Likelihood × Impact matrix" info={{
          what: "A 3×3 grid plotting the likelihood of a risk occurring against its potential impact. Cells flagged with a dot have at least one open risk register entry.",
          calculation: "Each open risk is placed in a cell by its assessed Likelihood (rows) and Impact (columns) score, both on a 1–3 scale, set during the monthly governance review.",
          source: "Risk Register, reviewed monthly by the Steering Committee" }}>
          <div className="grid grid-cols-3 grid-rows-3 gap-1.5 aspect-square text-[10px]">
            {Array.from({length:9}).map((_,i)=>{
              const row = Math.floor(i/3), col = i%3;
              const tone = (row+col) > 3 ? "bg-danger/40" : (row+col) > 1 ? "bg-accent/40" : "bg-success/30";
              const flag = [0,4,5,8].includes(i);
              return <div key={i} className={`rounded ${tone} relative grid place-items-center text-foreground/70 font-medium`}>{flag && <div className="size-3 rounded-full bg-danger" />}</div>;
            })}
          </div>
        </Panel>
        <Panel title="AI Recommendations" info={{
          what: "Suggested interventions generated by combining the Grant Risk Scorer, Learner Completion Predictor, and labour market signals.",
          calculation: "Recommendations are ranked by projected impact and only surfaced above a minimum confidence threshold.",
          source: "mart.grants · mart.completion_rates · labour_market_signals" }}>
          <ul className="space-y-2">
            {aiRecommendations.map(r=>(
              <li key={r.id ?? r.title} className="rounded-md border border-border p-2.5">
                <div className="flex items-center justify-between gap-2 text-xs">
                  <span className="font-medium">{r.title}</span>
                  <Badge tone={r.priority==="Critical"?"danger":"warn"}>{r.priority}</Badge>
                </div>
                <div className="text-[11px] text-muted-foreground mt-1">{r.rationale}</div>
              </li>
            ))}
          </ul>
        </Panel>
      </div>
    </>
  );
}
